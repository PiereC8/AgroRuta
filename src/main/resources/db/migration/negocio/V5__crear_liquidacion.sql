CREATE TABLE liquidacion (
    id_liquidacion           BIGINT         NOT NULL AUTO_INCREMENT,
    id_lote                  BIGINT         NOT NULL,
    id_pedido                BIGINT         NOT NULL,
    id_envio                 BIGINT         NOT NULL,
    cantidad_despachada_kg   DECIMAL(10, 3) NOT NULL,
    cantidad_recibida_kg     DECIMAL(10, 3) NOT NULL,
    merma_kg                 DECIMAL(10, 3) NOT NULL,
    rechazo_kg               DECIMAL(10, 3) NOT NULL,
    precio_acordado_kg       DECIMAL(10, 2) NOT NULL,
    costo_flete_kg           DECIMAL(10, 2) NOT NULL,
    ingreso_real             DECIMAL(18, 2) NOT NULL,
    costo_flete_total        DECIMAL(18, 2) NOT NULL,
    ganancia_real            DECIMAL(18, 2) NOT NULL,
    ganancia_esperada        DECIMAL(18, 2) NOT NULL,
    perdida_merma_rechazo    DECIMAL(18, 2) NOT NULL,
    usuario_entrega          VARCHAR(50)    NOT NULL,
    fecha_entrega            TIMESTAMP      NOT NULL,
    PRIMARY KEY (id_liquidacion),
    UNIQUE KEY uk_liquidacion_lote (id_lote),
    UNIQUE KEY uk_liquidacion_envio (id_envio),
    KEY ix_liquidacion_fecha (fecha_entrega),
    CONSTRAINT fk_liquidacion_lote FOREIGN KEY (id_lote) REFERENCES lote (id_lote),
    CONSTRAINT fk_liquidacion_pedido FOREIGN KEY (id_pedido) REFERENCES pedido (id_pedido),
    CONSTRAINT fk_liquidacion_envio FOREIGN KEY (id_envio) REFERENCES envio (id_envio)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4;
